import json,re
def slug(s): return re.sub(r'^-|-$','',re.sub(r'[^a-z0-9]+','-',re.sub(r'[—–→]',' ',s.lower())))
iv=json.load(open('seed_intervals.json'))
EX={}
def vname_from(name): 
    v=name.replace('KB ','kettlebell ').replace('—',',').replace('→','into').replace('&','and').replace('+','and')
    v=re.sub(r'\(.*?\)','',v); v=re.sub(r'\s+',' ',v).strip(' ,').lower()
    return v
for k,e in iv['exercises'].items():
    EX[k]=dict(id=k,name=e['name'],vname=vname_from(e['name']),cue=e['cue'],q=e['q'],bell=e['bell'],mode='time',reps='10',work=40,trans=10,tags=[])
workouts=[]
for w in iv['workouts']:
    for b in w['blocks']:
        for it in b['items']:
            it['reps']=''
    w['durationSec']=0; w['notes']=''
    workouts.append(w)
amraps=[('build_amrap.py','Bell Circuit A',1800),('build_amrap_b.py','Bell Circuit B',1800),('build_amrap_c.py','Bell Circuit C',1800),('build_amrap_d.py','Bell Circuit D',2400)]
for fn,title,dur in amraps:
    s=open(fn).read(); a=s.index('CIRCUIT=['); b=s.index('\n]',a)+2
    items=eval(s[a+8:b])
    ins=re.findall(r'CIRCUIT\.insert\((\d+),dict\(cardio=True\)\)',s)
    out=[]
    for d in items:
        k=slug(d['name'])
        v=re.sub(r'^\d+\s+','',d['say']); v=re.sub(r'\s+each (side|way)$','',v)
        if k not in EX: EX[k]=dict(id=k,name=d['name'],vname=v,cue=d['cue'],q=d['q'],bell=d['bell'] or '',mode='reps',reps=d['reps'],work=40,trans=10,tags=[])
        out.append(dict(kind='move',exId=k,mode='reps',reps=d['reps'],work=40,trans=10,bell=d['bell'] or ''))
    for i in ins: out.insert(int(i),dict(kind='cardio'))
    workouts.append(dict(id=slug(title),name=title,type='amrap',durationSec=dur,countdown=10,cardio=dict(type='mix',len=30),notes='',
        blocks=[dict(name='Circuit',rounds=0,restAfterRound=60,items=out)]))
seed=dict(version=1,bells=[30,35,45,55,60],exercises=list(EX.values()),workouts=workouts)
js='// Generated by tools/make_seed.py. Default library and workouts.\nexport const SEED = '+json.dumps(seed,indent=1,ensure_ascii=False)+';\n'
open('/home/claude/kettlebell-app/js/seed.js','w').write(js)
json.dump(seed,open('seed_full.json','w'))
print(len(EX),'exercises',len(workouts),'workouts')
